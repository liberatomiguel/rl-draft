#!/usr/bin/env node
/**
 * Writes docs/COSMETICS-CATALOG.md from the hand-maintained catalog
 * (src/data/cosmetics.ts) + the EN copy: every item, its kind, tier, unlock
 * rule and whether it is exclusive. Miguel reviews THIS file to decide which
 * items exist and how they unlock; edit the catalog + copy, then re-run:
 *
 *   node scripts/cosmetics-catalog.mjs
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const out = "/tmp/rd-cosmetics-catalog.mjs";
writeFileSync(
  "/tmp/rd-cosmetics-entry.ts",
  `export { COSMETICS } from "@/data/cosmetics";\nexport { EN } from "@/content/copy.en";\nexport { PT } from "@/content/copy.pt";\n`,
);
await build({
  entryPoints: ["/tmp/rd-cosmetics-entry.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: out,
  logLevel: "silent",
  alias: { "@": `${process.cwd()}/src` },
  absWorkingDir: process.cwd(),
});
const { COSMETICS, EN, PT } = await import(pathToFileURL(out).href);

const RANKS = { bronze: "Bronze", silver: "Silver", gold: "Gold", platinum: "Platinum", diamond: "Diamond", champion: "Champion", "grand-champion": "Grand Champion", "supersonic-legend": "Supersonic Legend" };
const unlock = (s) => {
  switch (s.type) {
    case "default": return "Everyone (starter)";
    case "legacy-participation": return "Pre-season: finished ≥1 run";
    case "legacy-rank": return `Pre-season peak rank ≥ ${RANKS[s.rankId] ?? s.rankId}`;
    case "legacy-position": return s.maxPosition === 1 ? "Pre-season board #1" : `Pre-season board top ${s.maxPosition}`;
    case "grant": return `Manual grant: ${s.grantId}`;
    case "season-rank": return `Season ${s.seasonId}: reach ${RANKS[s.rankId] ?? s.rankId}`;
    case "login-streak": return `Login streak ${s.days} days`;
    case "challenge-stars": return `${s.stars} challenge stars`;
    case "quiz-solved": return `${s.count} daily quizzes solved`;
    case "missions-completed": return `${s.count} missions completed`;
    case "career-mark": return `Road to Worlds achievement \`${s.markId}\``;
    default: return s.type;
  }
};
const style = (c) => {
  const st = c.style;
  switch (c.kind) {
    case "avatar": return `${st.motif} · ${st.colors.join(" → ")}`;
    case "badge": return `${st.shape} · ${st.glyph}${st.pips ? ` · ${st.pips} pips` : ""}${st.gem ? " · gem" : ""}${st.wings ? " · wings" : ""}`;
    case "frame": return `${st.shape} · weight ${st.weight}${st.studs ? " · studs" : ""}${st.animated ? ` · ${st.animated}` : ""}`;
    case "banner": return `${st.pattern ?? "none"}${st.animated ? " · animated" : ""}`;
    case "title": return `${st.color}${st.fx ? ` · ${st.fx}` : ""}`;
  }
};

const KIND_ORDER = ["avatar", "badge", "frame", "title", "banner"];
const TIER_ORDER = ["common", "rare", "epic", "legend"];
const lines = [];
lines.push("# Cosmetics catalog (v2.0 · rc.2)");
lines.push("");
lines.push("> GENERATED by `node scripts/cosmetics-catalog.mjs` from `src/data/cosmetics.ts` + `src/content/copy.en.ts` — do not hand-edit.");
lines.push("> To change an item: edit the catalog (style / unlock) and the EN + PT copy (name / description), then re-run the script.");
lines.push("> Tiers: **Basic** (flat, one colour) · **Rare** (two-tone + rim) · **Epic** (metal rim, gem, glow) · **Legend** (wings / laurels, sparkle, holo).");
lines.push("> *Exclusive* = can no longer be earned (pre-season legacy, manual grants); the locker hides it unless owned.");
lines.push("");
lines.push(`Total: **${COSMETICS.length}** items — ${KIND_ORDER.map((k) => `${COSMETICS.filter((c) => c.kind === k).length} ${k}s`).join(" · ")}.`);
lines.push("");
for (const kind of KIND_ORDER) {
  const items = COSMETICS.filter((c) => c.kind === kind).sort((a, b) => TIER_ORDER.indexOf(a.tier) - TIER_ORDER.indexOf(b.tier) || b.priority - a.priority);
  lines.push(`## ${kind[0].toUpperCase()}${kind.slice(1)}s (${items.length})`);
  lines.push("");
  lines.push("| Id | Name (EN / PT) | Tier | Unlock | Exclusive | Look | Description (EN) |");
  lines.push("|---|---|---|---|---|---|---|");
  for (const c of items) {
    const en = EN.COSMETICS.items[c.id] ?? { name: c.id, desc: "" };
    const pt = PT.COSMETICS.items[c.id] ?? { name: c.id, desc: "" };
    lines.push(`| \`${c.id}\` | ${en.name} / ${pt.name} | ${EN.COSMETICS.tiers[c.tier] ?? c.tier} | ${unlock(c.source)} | ${c.exclusive ? "yes" : ""} | ${style(c)} | ${en.desc} |`);
  }
  lines.push("");
}
lines.push("## Unlock sources at a glance");
lines.push("");
const bySource = new Map();
for (const c of COSMETICS) {
  const k = unlock(c.source);
  if (!bySource.has(k)) bySource.set(k, []);
  bySource.get(k).push(`${c.kind}: ${EN.COSMETICS.items[c.id]?.name ?? c.id}`);
}
for (const [k, v] of [...bySource.entries()].sort((a, b) => a[0].localeCompare(b[0]))) lines.push(`- **${k}** → ${v.join(", ")}`);
lines.push("");
writeFileSync("docs/COSMETICS-CATALOG.md", lines.join("\n"));
console.log(`wrote docs/COSMETICS-CATALOG.md (${COSMETICS.length} items)`);
