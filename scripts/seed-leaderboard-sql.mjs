#!/usr/bin/env node
/**
 * Writes docs/sql/seed-staging-leaderboard.sql — ~60 fictional players for the
 * STAGING Supabase project, so the boards can be reviewed full. Same rows as the
 * in-app preview fixture (src/data/previewLeaderboard.ts).
 *
 *   node scripts/seed-leaderboard-sql.mjs
 *
 * NEVER run the SQL against production: it inserts auth.users rows.
 */
// rc.4: bundled with rolldown (the bundler Vite ships) — esbuild is no longer installed.
import { build } from "rolldown";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const out = join(mkdtempSync(join(tmpdir(), "rd-seed-")), "preview-leaderboard.mjs");
await build({
  input: "src/data/previewLeaderboard.ts",
  platform: "node",
  logLevel: "silent",
  resolve: { alias: { "@": join(process.cwd(), "src") } },
  output: { file: out, format: "esm" },
});
const { previewLeaderboardRows } = await import(pathToFileURL(out).href);

const uuid = (name) => {
  const h = createHash("sha1").update(`rocket-draft-seed:${name}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `'{${a.map((x) => `"${x}"`).join(",")}}'`;

const rows = previewLeaderboardRows();
const lines = [];
lines.push(`-- Rocket Draft — STAGING leaderboard seed (generated by scripts/seed-leaderboard-sql.mjs).`);
lines.push(`-- ${rows.length} fictional players. Run in the staging project's SQL editor AFTER the v2.0 schema.`);
lines.push(`-- NEVER run against production.`);
lines.push(`begin;`);
for (const r of rows) {
  const id = uuid(r.username);
  const email = `seed-${r.username.toLowerCase().replace(/[^a-z0-9]/g, "")}@rocketdraft.invalid`;
  lines.push(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)` +
      ` values ('00000000-0000-0000-0000-000000000000', '${id}', 'authenticated', 'authenticated', ${q(email)}, crypt('seed-only', gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '') on conflict (id) do nothing;`,
  );
  lines.push(
    `insert into public.profiles (id, username, xp, mmr, season_id, season_xp, season_mmr, season_peak_mmr, season_titles, season_runs, lifetime_xp, championships, best_legacy, best_sam, quiz_solved, login_streak, challenge_stars, equipped_title, equipped_frame, equipped_banner, equipped_badges, preseason_position)` +
      ` values ('${id}', ${q(r.username)}, ${r.preseason_xp}, ${r.preseason_mmr}, 1, ${r.season_xp}, ${r.season_mmr}, ${r.season_peak_mmr}, ${r.season_titles}, ${r.season_runs}, ${r.lifetime_xp}, ${r.championships}, ${r.best_legacy}, ${r.best_sam}, ${r.quiz_solved}, ${r.login_streak}, ${r.challenge_stars}, ${q(r.equipped_title)}, ${q(r.equipped_frame)}, ${q(r.equipped_banner)}, ${arr(r.equipped_badges)}, ${r.preseason_position ?? "null"})` +
      ` on conflict (id) do update set username = excluded.username, season_xp = excluded.season_xp, season_mmr = excluded.season_mmr, season_peak_mmr = excluded.season_peak_mmr, season_titles = excluded.season_titles, season_runs = excluded.season_runs, lifetime_xp = excluded.lifetime_xp, championships = excluded.championships, best_legacy = excluded.best_legacy, best_sam = excluded.best_sam, quiz_solved = excluded.quiz_solved, login_streak = excluded.login_streak, challenge_stars = excluded.challenge_stars, equipped_title = excluded.equipped_title, equipped_frame = excluded.equipped_frame, equipped_banner = excluded.equipped_banner, equipped_badges = excluded.equipped_badges;`,
  );
  for (const g of r.grants) {
    lines.push(`insert into public.profile_grants (user_id, grant_id, note) values ('${id}', '${g}', 'staging seed') on conflict do nothing;`);
  }
}
lines.push(`commit;`);
lines.push(`-- Clean-up: delete from auth.users where email like 'seed-%@rocketdraft.invalid'; (profiles cascade)`);
mkdirSync("docs/sql", { recursive: true });
writeFileSync("docs/sql/seed-staging-leaderboard.sql", lines.join("\n") + "\n");
console.log(`wrote docs/sql/seed-staging-leaderboard.sql (${rows.length} players)`);
