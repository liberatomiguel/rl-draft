#!/usr/bin/env node
/**
 * rc.4 — exports the badge art from Miguel's design file
 * (`data-sources/badges/badges-gema-moldura.html`, the "Gema & Moldura"
 * generator) into one static SVG per badge: `public/badges/<art>.svg`.
 *
 * The HTML carries a self-contained generator (`badgeSVG(spec)`, the `SERIES`
 * catalog and `rankBadge(rank, season)`); everything after it is page wiring
 * that touches the DOM. We evaluate ONLY the generator part, in an empty
 * `node:vm` context (no require, no process, no fs), and write every badge of
 * every series as `<key>.svg` (the approved catalog). Season rank badges
 * (`rankBadge(rank, season)`) are handed out at a season's turnover and get
 * exported here when that season's set is added to the catalog (rc.6: none yet).
 * Then it checks that every badge art key in `src/data/cosmetics.ts` exists.
 *
 * When Miguel sends a new design file: replace the HTML, run
 * `npm run build:badges`, commit `public/badges/`.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import vm from "node:vm";

const SRC = "data-sources/badges/badges-gema-moldura.html";
const OUT = "public/badges";
/** Season rank badges to export: [rank key in the file, season key] (none yet). */
const SEASON_RANK_BADGES = [];

const html = readFileSync(SRC, "utf8");
const open = html.lastIndexOf("<script>");
if (open < 0) throw new Error(`${SRC}: no <script> block`);
const script = html.slice(open + "<script>".length, html.indexOf("</script>", open));
// The generator ends where the page wiring begins (the first DOM write).
const domStart = script.search(/^document\./m);
const generator = domStart > 0 ? script.slice(0, domStart) : script;

const sandbox = vm.createContext({});
vm.runInContext(`${generator}\n;globalThis.__out = { SERIES, badgeSVG, rankBadge };`, sandbox, { timeout: 10_000 });
const { SERIES, badgeSVG, rankBadge } = sandbox.__out;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const written = [];
const write = (key, spec) => {
  if (!/^[a-z0-9-]+$/.test(key)) throw new Error(`unsafe badge key: ${key}`);
  const svg = String(badgeSVG({ ...spec, id: key, size: 256 }));
  if (!svg.startsWith("<svg")) throw new Error(`${key}: generator did not return an SVG`);
  writeFileSync(join(OUT, `${key}.svg`), `${svg}\n`);
  written.push([key, spec.name ?? key, svg.length]);
};
for (const serie of SERIES) for (const b of serie.badges) write(b.key, b);
for (const [rank, season] of SEASON_RANK_BADGES) {
  const b = rankBadge(rank, season);
  write(b.key, b);
}

// Every art key the catalog references must exist.
const catalog = readFileSync("src/data/cosmetics.ts", "utf8");
const arts = new Set([...catalog.matchAll(/art:\s*"([a-z0-9-]+)"/g)].map((m) => m[1]));
const ids = new Set([...catalog.matchAll(/badge\("([a-z0-9-]+)"/g)].map((m) => m[1]));
const files = new Set(readdirSync(OUT).map((f) => f.replace(/\.svg$/, "")));
const missing = [...arts, ...ids].filter((k) => !files.has(k));
if (missing.length) throw new Error(`badge art missing for: ${missing.join(", ")}`);

writeFileSync(
  join(OUT, "README.md"),
  [
    "# Badge art (generated)",
    "",
    "GENERATED by `npm run build:badges` from `data-sources/badges/badges-gema-moldura.html` — do not hand-edit.",
    "Replace the design file and re-run the script to update the art.",
    "",
    "| File | Name |",
    "|---|---|",
    ...written.map(([key, name]) => `| \`${key}.svg\` | ${name} |`),
    "",
  ].join("\n"),
);

const kb = written.reduce((n, [, , len]) => n + len, 0) / 1024;
console.log(`wrote ${written.length} badges to ${OUT}/ (${kb.toFixed(0)} KB raw)`);
