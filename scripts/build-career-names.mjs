import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../data-sources/career/names.json", import.meta.url);
const catalog = JSON.parse(await readFile(source, "utf8"));
for (const type of ["players", "orgs"]) {
  for (const [region, names] of Object.entries(catalog[type])) {
    if (!names.length || new Set(names.map(n => n.toLocaleLowerCase())).size !== names.length) throw new Error(`Invalid ${type} pool: ${region}`);
  }
}
await writeFile(new URL("../src/data/career/nameCatalog.ts", import.meta.url),
  `// Generated by scripts/build-career-names.mjs from the approved workbook import.\nexport const NAME_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`);
console.log("Career name catalog generated.");
